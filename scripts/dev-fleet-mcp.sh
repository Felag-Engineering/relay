#!/usr/bin/env bash
# Raw JSON-RPC poker for the dev fleet's MCP endpoint (docs/dev-fleet.md).
# DEV-ONLY. Nothing in the build/test/lint gate calls this.
#
# WHY THIS EXISTS. Relay's /mcp serves the MCP Tasks extension (SEP-2663,
# ADR-0028), but no shipping MCP client implements it — not the Go SDK
# (go-sdk#626), not the TypeScript or Python ones. So `tasks/get`,
# `tasks/cancel`, and the CreateTaskResult shim cannot be exercised by pointing
# a normal client at the fleet: the capability that triggers them is advertised
# in a per-request `_meta` no client sends. This script speaks the wire by hand
# so those paths are reachable at all.
#
# It is deliberately NOT a client library. It is a curl wrapper that lets a
# human (or an AI-agent driving a terminal) see exactly what goes over the wire,
# which is the only way to check Relay's reading of a spec no one else has
# implemented yet.
#
# The /mcp handler is stateless (SEP-2575 puts client capabilities in per-request
# `_meta`), so there is no `initialize` handshake to maintain here — every call
# below is a single self-contained POST.
set -euo pipefail

STATE_DIR="${STATE_DIR:-.dev-fleet}"
CA="${STATE_DIR}/ca-cert.pem"
ADMIN_CRED="${STATE_DIR}/control-credential"
APPROVER_CRED="${STATE_DIR}/approver-credential"
BASE="${BASE:-https://localhost:9443}"

# The Relay's server cert SAN is `relay` (the in-fleet DNS name), not localhost.
# --resolve maps the name to loopback so TLS is VERIFIED against the real CA
# rather than skipped with -k. A dev script that teaches "just use -k" is a bad
# habit to hand an operator.
RESOLVE=(--resolve "relay:9443:127.0.0.1")
MCP_BASE="https://relay:9443"

die() { echo "dev-fleet-mcp: $*" >&2; exit 1; }

usage() {
    cat >&2 <<'USAGE'
Usage: scripts/dev-fleet-mcp.sh <command> [args]

  init                       Export the CA cert and both credentials to .dev-fleet/
  creds                      Print the admin credential (for an MCP client config)
  creds-approver             Print the approver credential

  call <tool> [json-args]    tools/call WITHOUT the Tasks capability
                             (what Claude Code and every real client sends today)
  call-tasks <tool> [json]   tools/call WITH the Tasks capability advertised
                             (a parked dispatch comes back as a task handle)
  task-get <taskId>          tasks/get
  task-cancel <taskId>       tasks/cancel
  raw <method> [json-params] Any JSON-RPC method, verbatim — including ones
                             Relay does not serve (try: raw tasks/update '{}')

  api <method> <path> [body] Control API call as the ADMIN account
  api-approver <m> <p> [b]   Control API call as the APPROVER account

Env: STATE_DIR (default .dev-fleet), BASE (default https://localhost:9443)
USAGE
    exit 2
}

need_state() {
    [[ -s "${CA}" ]] || die "no ${CA} — run: scripts/dev-fleet-mcp.sh init"
}

cmd_init() {
    mkdir -p "${STATE_DIR}"
    docker compose cp relay:/var/lib/relay/ca/ca-cert.pem "${CA}" >/dev/null
    # The credentials live on the control-credential volume, which only the
    # minting services mount. `run --no-deps` attaches a throwaway container to
    # read them out without disturbing the fleet.
    docker compose run --rm --no-deps --entrypoint sh approver \
        -c 'cat /credential/control-credential' 2>/dev/null | tr -d '\r' > "${ADMIN_CRED}"
    docker compose run --rm --no-deps --entrypoint sh approver \
        -c 'cat /credential/approver-credential' 2>/dev/null | tr -d '\r' > "${APPROVER_CRED}"
    chmod 0600 "${ADMIN_CRED}" "${APPROVER_CRED}"
    [[ -s "${ADMIN_CRED}" ]]    || die "admin credential came back empty — is the fleet up?"
    [[ -s "${APPROVER_CRED}" ]] || die "approver credential came back empty — did the approver service run?"
    write_start_note
    echo "dev-fleet-mcp: CA cert and both credentials are in ${STATE_DIR}/"
    echo "dev-fleet-mcp: copy-paste launch commands: ${STATE_DIR}/start-claude.txt"
}

# The CA is regenerated by `compose down -v`, which also invalidates every
# credential. Rewriting this note on every init keeps the paths and the recovery
# steps correct rather than something remembered from a previous fleet.
write_start_note() {
    local abs; abs="$(cd "${STATE_DIR}" && pwd)"
    cat > "${STATE_DIR}/start-claude.txt" <<EOF
# Start Claude Code trusting the dev fleet's private CA.
# Without this the relay MCP server fails with UNABLE_TO_VERIFY_LEAF_SIGNATURE.

NODE_EXTRA_CA_CERTS=${abs}/ca-cert.pem claude


# --- or set it once for the shell ---

export NODE_EXTRA_CA_CERTS=${abs}/ca-cert.pem


# --- if the fleet was wiped with 'down -v', the CA and token are stale ---

make dev-fleet-creds
claude mcp remove relay
claude mcp add --transport http relay https://relay:9443/mcp \\
  --header "Authorization: Bearer \$(cat ${abs}/control-credential)"
EOF
}

# mcp_post <credential-file> <method> <params-json> <tasks-capable:true|false> [tool-name]
mcp_post() {
    local credfile="$1" method="$2" params="$3" capable="$4" toolname="${5-}"
    need_state
    local cred; cred="$(cat "${credfile}")"

    # Per-request client capabilities (SEP-2575). The Tasks extension key is
    # what flips Relay's shim from a plain tool result to a task handle.
    local caps='{}'
    if [[ "${capable}" == "true" ]]; then
        caps='{"extensions":{"io.modelcontextprotocol/tasks":{}}}'
    fi
    local meta
    meta=$(printf '{"io.modelcontextprotocol/protocolVersion":"2026-07-28",'
           printf '"io.modelcontextprotocol/clientInfo":{"name":"dev-fleet-mcp","version":"0.0.1"},'
           printf '"io.modelcontextprotocol/clientCapabilities":%s}' "${caps}")

    # Splice _meta into the caller's params object.
    local body
    body=$(printf '{"jsonrpc":"2.0","id":1,"method":"%s","params":%s}' \
        "${method}" \
        "$(printf '%s' "${params}" | META="${meta}" python3 -c '
import json,sys,os
p = json.load(sys.stdin)
p["_meta"] = json.loads(os.environ["META"])
print(json.dumps(p))')")

    # From 2026-07-28 a tools/call MUST also echo the tool name in a header, so a
    # proxy can route without parsing the body. Relay enforces this.
    local name_header=()
    [[ -n "${toolname}" ]] && name_header=(-H "Mcp-Name: ${toolname}")

    curl -sS "${RESOLVE[@]}" --cacert "${CA}" \
        -H "Authorization: Bearer ${cred}" \
        -H 'Content-Type: application/json' \
        -H 'Accept: application/json, text/event-stream' \
        -H 'MCP-Protocol-Version: 2026-07-28' \
        "${name_header[@]}" \
        -H "Mcp-Method: ${method}" \
        -X POST "${MCP_BASE}/mcp" \
        --data-binary "${body}" \
    | python3 -c 'import json,sys
raw = sys.stdin.read()
# A Streamable-HTTP response may arrive as SSE; take the last data: frame.
if raw.lstrip().startswith("event:") or "\ndata:" in raw or raw.startswith("data:"):
    frames = [l[5:].strip() for l in raw.splitlines() if l.startswith("data:")]
    raw = frames[-1] if frames else raw
try:
    print(json.dumps(json.loads(raw), indent=2))
except Exception:
    print(raw)'
}

# api_call <credential-file> <http-method> <path> [body]
api_call() {
    local credfile="$1" method="$2" path="$3" body="${4:-}"
    need_state
    local cred; cred="$(cat "${credfile}")"
    local args=(-sS "${RESOLVE[@]}" --cacert "${CA}"
                -H "Authorization: Bearer ${cred}"
                -X "${method}" "https://relay:9443${path}")
    if [[ -n "${body}" ]]; then
        args+=(-H 'Content-Type: application/json' --data-binary "${body}")
    fi
    curl "${args[@]}" | python3 -c 'import json,sys
raw = sys.stdin.read()
try:
    print(json.dumps(json.loads(raw), indent=2))
except Exception:
    print(raw)'
}

tool_params() {
    local tool="$1" args="${2-}"
    [[ -n "${args}" ]] || args='{}'
    printf '{"name":"%s","arguments":%s}' "${tool}" "${args}"
}

# empty_obj echoes its argument, defaulting to an empty JSON object.
empty_obj() { local v="${1-}"; [[ -n "${v}" ]] && printf '%s' "${v}" || printf '{}'; }

[[ $# -ge 1 ]] || usage
case "$1" in
    init)           cmd_init ;;
    creds)          need_state; cat "${ADMIN_CRED}" ;;
    creds-approver) need_state; cat "${APPROVER_CRED}" ;;
    call)           [[ $# -ge 2 ]] || usage
                    mcp_post "${ADMIN_CRED}" tools/call "$(tool_params "$2" "${3-}")" false "$2" ;;
    call-tasks)     [[ $# -ge 2 ]] || usage
                    mcp_post "${ADMIN_CRED}" tools/call "$(tool_params "$2" "${3-}")" true "$2" ;;
    task-get)       [[ $# -ge 2 ]] || usage
                    mcp_post "${ADMIN_CRED}" tasks/get "$(printf '{"taskId":"%s"}' "$2")" true ;;
    task-cancel)    [[ $# -ge 2 ]] || usage
                    mcp_post "${ADMIN_CRED}" tasks/cancel "$(printf '{"taskId":"%s"}' "$2")" true ;;
    raw)            [[ $# -ge 2 ]] || usage
                    mcp_post "${ADMIN_CRED}" "$2" "$(empty_obj "${3-}")" true ;;
    api)            [[ $# -ge 3 ]] || usage; api_call "${ADMIN_CRED}"    "$2" "$3" "${4:-}" ;;
    api-approver)   [[ $# -ge 3 ]] || usage; api_call "${APPROVER_CRED}" "$2" "$3" "${4:-}" ;;
    *)              usage ;;
esac
