#!/usr/bin/env bash
# Generate docs/adr/README.md — the ADR index — from the ADR files themselves: number and title
# from each file's H1, status from its `**Status:**` header, and the amendment links from the
# wording scripts/adr-links.sh reads. Nothing here is hand-kept; `make adr-index` regenerates the
# file and scripts/check-crosslinks.sh fails when the committed copy differs (drift gate).
#
#   scripts/adr-index.sh            print the index to stdout
#   make adr-index                  write it to docs/adr/README.md
set -euo pipefail
cd "$(dirname "$0")/.."
# shellcheck source=scripts/adr-links.sh
source scripts/adr-links.sh

declare -A title status amends amended_by file
numbers=()
for f in docs/adr/[0-9]*.md; do
  n=$(adr_number "$f")
  numbers+=("$n"); file[$n]=$f
  title[$n]=$(adr_title "$f" | sed 's/|/\\|/g')
  status[$n]=$(adr_status "$f"); : "${status[$n]:=—}"
  amends[$n]=$(adr_amends "$f" | tr '\n' ' ')
done
# Links run both ways. An ADR's own header ("amended by ADR-X") records that X amends it, so X
# gains a forward link and this ADR a reverse one; an in-force ADR that says it amends Y gives
# Y a reverse link. An ADR that is Proposed or Deferred amends nothing, so it contributes none.
for n in "${numbers[@]}"; do
  f=${file[$n]}
  for x in $(adr_header_amended_by "$f"); do amended_by[$n]+="$x "; amends[$x]+="$n "; done
done
for n in "${numbers[@]}"; do
  adr_in_force "${file[$n]}" || continue
  for x in $(adr_amends "${file[$n]}"); do amended_by[$x]+="$n "; done
done

link() {                              # link <NNNN>  →  [ADR-NNNN](NNNN-slug.md), or plain when absent
  local f; f=$(adr_file "$1") && echo "[ADR-$1]($(basename "$f"))" || echo "ADR-$1"
}
cell() {                              # cell <space-separated numbers>  →  links joined, or —
  local out="" n
  for n in $(printf '%s\n' $1 | sort -u); do out+="${out:+, }$(link "$n")"; done
  echo "${out:-—}"
}

cat <<'EOF'
# Architecture decision records

<!-- GENERATED by scripts/adr-index.sh — do not edit by hand. Regenerate with `make adr-index`;
     `make docs-check` fails while this file differs from the generator's output. -->

Each ADR records a decision that is hard to reverse, surprising without context, and the
result of a real trade-off. The status is the ADR's own `**Status:**` header. *Amends* is what
the ADR's text says it amends or supersedes, plus what another ADR's header records as amended
by it; *Amended by* is the reverse. A Proposed or Deferred ADR amends nothing. The reading rules
are in `scripts/adr-links.sh`; `scripts/check-crosslinks.sh` fails a PR whose amendment has no
back-link.

| ADR | Title | Status | Amends | Amended by |
|---|---|---|---|---|
EOF
for n in "${numbers[@]}"; do
  printf '| %s | %s | %s | %s | %s |\n' \
    "$(link "$n")" "${title[$n]}" "${status[$n]}" "$(cell "${amends[$n]}")" "$(cell "${amended_by[$n]:-}")"
done
