// OAuth 2.1 protected-resource support for the MCP endpoint (#299, ADR-0024).
//
// The Relay validates tokens an external IdP issued and resolves them to
// Accounts. It is **not** an authorization server: no authorization endpoint,
// no token endpoint, no client registration, no consent screen. See ADR-0024
// for why that is not a close call — an authorization-code flow needs a
// browser-facing login and consent surface, and the Relay has no web UI and no
// human credential at all.
//
// What an OAuth session buys is **attribution and revocation, not trust**. It
// proves a human authorized the *session*; the individual tool calls are still
// generated by a model that may have read attacker-controlled content. MCP
// calls therefore remain AI-agent-grade for approval gating (v0.5.0) no matter
// whose identity authorizes the session.

// ProtectedResourceMetadataPath is where RFC 9728 metadata is served. Fixed by
// the RFC — a harness looks here without being told to.
const ProtectedResourceMetadataPath = "/.well-known/oauth-protected-resource"

// OIDCVerifier verifies a raw JWT and returns its claims. *oidc.IDTokenVerifier
// satisfies it.
//
// An interface rather than the concrete type so tests can drive the whole
// resolution path with a locally-signed token and no live IdP — an auth path
// that can only be tested against a real provider is one that goes untested.
type OIDCVerifier interface {
	Verify(ctx context.Context, rawIDToken string) (*oidc.IDToken, error)
}

// OAuthConfig configures the resource-server half.
//
// This is Relay configuration (invariant 11): it comes from flags and a
// root-owned local file, and is never reachable through the Control API. An
// API that could repoint its own issuer could authenticate anyone.
type OAuthConfig struct {
	// Issuer is the IdP's issuer identifier, used for discovery and checked
	// against every token's `iss`.
	Issuer string

	// Audience is this Relay's resource identifier — the MCP endpoint's URL —
	// checked against every token's `aud`.
	//
	// This is the RFC 8707 audience binding, and it is what stops a token
	// minted for some other service in the same IdP from driving the fleet.
	// Without it, any application sharing the IdP becomes a confused deputy.
	Audience string

	// AccountClaim names the claim whose value maps to an Account name.
	// Defaults to "email".
	AccountClaim string

	// RequiredScope, if set, must appear in the token's `scope` claim.
	RequiredScope string
}

// oauthResolver turns a verified token into an Account.
type oauthResolver struct {
	verifier     OIDCVerifier
	accounts     AccountLookup
	accountClaim string
	scope        string
	issuer       string
	audience     string

	// metadataURL is advertised in WWW-Authenticate so a harness can discover
	// the flow.
	metadataURL string
}

// AccountLookup is the narrow Account-store view OAuth resolution needs.
//
// Read-only by construction: resolving a session must never be able to create
// an Account. Auto-provisioning from a token claim would let whoever
// administers the IdP mint identities on the control plane, bypassing the
// audited creation path (#297).
type AccountLookup interface {
	GetByName(ctx context.Context, name string) (accounts.Account, error)
}

// errOAuthUnauthenticated is the single internal failure for every OAuth
// rejection. Like the API Token path, the caller learns nothing about which
// check failed.
var errOAuthUnauthenticated = errors.New("controlplane: oauth token rejected")

// resolve verifies a JWT and returns the Account it authenticates as.
//
// Every failure — bad signature, wrong issuer, wrong audience, expired,
// missing claim, unknown Account, disabled Account, missing scope — returns
// the same error. The IdP told the caller their token was fine; the Relay
// telling them *which* of its own checks then rejected it would only help
// someone probing for a valid identity.
func (o *oauthResolver) resolve(ctx context.Context, raw string) (capability.Principal, error) {
	tok, err := o.verifier.Verify(ctx, raw)
	if err != nil {
		return capability.Principal{}, errOAuthUnauthenticated
	}

	var claims map[string]any
	if err := tok.Claims(&claims); err != nil {
		return capability.Principal{}, errOAuthUnauthenticated
	}

	if o.scope != "" && !hasScope(claims, o.scope) {
		return capability.Principal{}, errOAuthUnauthenticated
	}

	name, _ := claims[o.accountClaim].(string)
	if name == "" {
		return capability.Principal{}, errOAuthUnauthenticated
	}

	acct, err := o.accounts.GetByName(ctx, accounts.NormalizeName(name))
	if err != nil {
		// Includes ErrNotFound: a human whose Account has not been created is
		// refused, not provisioned. See ADR-0024.
		return capability.Principal{}, errOAuthUnauthenticated
	}
	if !acct.Enabled {
		return capability.Principal{}, errOAuthUnauthenticated
	}

	// No TokenID: an OAuth session presents no API Token. The verified lane
	// records the method instead, which is what makes the two session kinds
	// distinguishable in audit (#300 acceptance).
	p := principalFromAccount(acct)
	p.AuthMethod = capability.AuthMethodOAuth
	return p, nil
}

// hasScope reports whether the token's space-delimited `scope` claim contains
// want. Exact element match — a substring check would let "read" match
// "readwrite".
func hasScope(claims map[string]any, want string) bool {
	raw, _ := claims["scope"].(string)
	for _, s := range strings.Fields(raw) {
		if s == want {
			return true
		}
	}
	return false
}

// NewOIDCVerifier builds a verifier by discovering issuer metadata and its
// JWKS. It performs network I/O and is called once, at startup, so a
// misconfigured issuer fails the Relay's boot rather than every request.
func NewOIDCVerifier(ctx context.Context, cfg OAuthConfig) (OIDCVerifier, error) {
	provider, err := oidc.NewProvider(ctx, cfg.Issuer)
	if err != nil {
		return nil, fmt.Errorf("controlplane: oauth discovery for issuer %q: %w", cfg.Issuer, err)
	}
	// ClientID carries the resource identifier: go-oidc checks it against the
	// token's `aud`, which is the RFC 8707 binding described on
	// OAuthConfig.Audience.
	return provider.Verifier(&oidc.Config{ClientID: cfg.Audience}), nil
}

// wwwAuthenticate returns the challenge value for a 401.
//
// With OAuth configured it carries the RFC 9728 `resource_metadata` pointer,
// which is the whole discovery mechanism: an off-the-shelf harness reads it,
// fetches the metadata, finds the authorization server, and runs the flow —
// with no Relay-specific configuration on the client side.
func (a *Authenticator) wwwAuthenticate() string {
	if a.oauth == nil || a.oauth.metadataURL == "" {
		return "Bearer"
	}
	return fmt.Sprintf(`Bearer resource_metadata=%q`, a.oauth.metadataURL)
}

// protectedResourceMetadata is the RFC 9728 document served at
// ProtectedResourceMetadataPath. Public by design — it names the
// authorization server and the resource identifier, and nothing else.
type protectedResourceMetadata struct {
	Resource               string   `json:"resource"`
	AuthorizationServers   []string `json:"authorization_servers"`
	BearerMethodsSupported []string `json:"bearer_methods_supported"`
	ScopesSupported        []string `json:"scopes_supported,omitempty"`
	ResourceName           string   `json:"resource_name,omitempty"`
}

// MetadataHandler serves the protected-resource metadata document, or 404 when
// OAuth is not configured — a Relay with no IdP advertises no flow rather than
// an empty one a harness would then fail to complete.
func (a *Authenticator) MetadataHandler() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if a.oauth == nil {
			http.NotFound(w, r)
			return
		}
		doc := protectedResourceMetadata{
			Resource:               a.oauth.audience,
			AuthorizationServers:   []string{a.oauth.issuer},
			BearerMethodsSupported: []string{"header"},
			ResourceName:           "Relay control plane",
		}
		if a.oauth.scope != "" {
			doc.ScopesSupported = []string{a.oauth.scope}
		}
		// Public discovery data, fetched cross-origin by browser-based
		// harnesses (RFC 9728 §3.1).
		w.Header().Set("Access-Control-Allow-Origin", "*")
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(doc)
	})
}
