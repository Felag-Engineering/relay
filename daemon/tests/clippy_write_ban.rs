/// `#[path = ..]` mounts and every use of the identifier `include` (so `include!`,
/// and an alias such as `use core::include as pull;`) per file: each pulls source in
/// from somewhere the walked tree might not show, so each is reviewed. This is the
/// SECOND layer; the compiled-file check below (from cargo's dep-info) is the first,
/// because a syntactic scan cannot see through every macro alias.
fn mounts(src: &str) -> (usize, usize) {
    let scrubbed = scrub(src, false);
    let paths = attributes(&scrubbed)
        .iter()
        .filter(|a| a.starts_with("[path=") || (a.starts_with("[cfg_attr(") && a.contains("path=")))
        .count();
    let includes = Regex::new(r"\binclude\b")
        .unwrap()
        .find_iter(&scrubbed)
        .count();
    (paths, includes)
}

