/// Every member's `[features]` table, exactly: feature name -> its (empty) member
/// list. No `default`, and no feature that forwards another crate's `test-util` or
/// `ban-probe` (`x = ["relay-ops/test-util"]`), because either would compile test-only
/// items (`TemplateSet::for_test`, `identity::mode_assert`) into the shipped binary.
fn pinned_features(name: &str) -> BTreeSet<&'static str> {
    let keys: &[&str] = match name {
        "relay-policy" | "relay-ops" => &["test-util", "ban-probe"],
        "relay-transport" => &["test-util"],
        "relay-log" | "relay-exec" | "relay-proto" => &["ban-probe"],
        "relay-daemon" | "relay-test-support" => &[],
        other => panic!("no pinned [features] table for member {other}"),
    };
    keys.iter().copied().collect()
}

