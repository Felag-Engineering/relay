/// The spawn family, matched on code with comments and literals blanked: the
/// `Command` type (an alias still names `Command` in its `use`), `pre_exec`, libc's
/// exec/fork/spawn functions (a brace import names them too), and `system`/`syscall`
/// calls. A word-boundary match, so `system_facts` and `ConnectFailure` are not
/// hits. A module alias (`use libc as l; l::syscall`) misses it; clippy's
/// resolved-path ban and the `unsafe` census catch that case.
fn spawn_family() -> Regex {
    Regex::new(
        r"\b(Command|CommandExt|pre_exec|fork|vfork|fexecve|execv|execve|execveat|execvp|execvpe|execl|execle|execlp|posix_spawn|posix_spawnp|popen)\b|\blibc::(system|syscall|clone|clone3)\b|\blibc::\{[^}]*\b(system|syscall|clone|clone3)\b|\b(system|syscall)\s*\(|\bSYS_(execve|execveat|fork|vfork|clone|clone3)\b",
    )
    .unwrap()
}

fn spawn_hits(src: &str) -> usize {
    spawn_family().find_iter(&scrub(src, true)).count()
}

/// Whether `rel` is a crate's probe file, which names banned calls on purpose.
fn is_probe_file(rel: &str) -> bool {
    rel.starts_with("crates/") && rel.ends_with("/ban_probe.rs")
}

/// Invariant 1: exactly two files build a process, each reviewed. clippy's
/// `Command::new` ban and the pinned allows are the first line; this is the second, because an
/// aliased `Command`, a brace-imported libc `fork`, or a `pre_exec` inside a
/// module-level lint allow passes clippy. It reads every crate and the bin.
#[test]
fn spawn_family_appears_only_at_the_sanctioned_sites() {
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    for (rel, src) in sources() {
        if is_probe_file(&rel) {
            continue;
        }
        let n = spawn_hits(&src);
        if n > 0 {
            seen.insert(rel, n);
        }
    }
    let want = BTreeMap::from([
        // The `use tokio::process::Command;` import, `Command::new`, and `cmd.pre_exec`.
        ("crates/relay-exec/src/executor.rs".to_string(), 3usize),
        // `join`'s import and its one `Command::new`.
        ("src/join/systemctl.rs".to_string(), 2usize),
    ]);
    assert_eq!(
        seen, want,
        "the spawn family (Command, pre_exec, libc exec/fork/system) must appear only at the \
         two sanctioned sites, relay-exec's executor.rs and join's systemctl module (AGENTS.md \
         invariant 1): another place that can build a process is a spawn path outside that review"
    );
}

