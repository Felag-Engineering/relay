/// The features cargo RESOLVES for `rustix` in the shipped (normal-edge) graph.
/// Calls `cargo tree` (offline, locked): it takes no build lock and needs no target
/// installed, since it only resolves.
#[allow(clippy::disallowed_methods)] // test-only: spawns `cargo tree`, as dev_fleet_fixtures.rs spawns its binary
fn resolved_rustix_features(target: Option<&str>) -> BTreeSet<String> {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    let mut cmd = std::process::Command::new(cargo);
    cmd.current_dir(daemon())
        .args([
            "tree",
            "--locked",
            "--offline",
            "-e",
            "normal",
            "-i",
            "rustix",
        ])
        .args(["-p", "relay-daemon", "-f", "{p} [{f}]"]);
    if let Some(t) = target {
        cmd.args(["--target", t]);
    }
    let out = cmd.output().expect("run cargo tree");
    assert!(
        out.status.success(),
        "cargo tree failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let text = String::from_utf8_lossy(&out.stdout).into_owned();
    let first = text.lines().next().expect("cargo tree printed nothing");
    assert!(
        first.starts_with("rustix "),
        "unexpected cargo tree output: {first}"
    );
    first
        .rsplit_once('[')
        .expect("feature list")
        .1
        .trim_end_matches(']')
        .split(',')
        .map(str::to_string)
        .collect()
}

