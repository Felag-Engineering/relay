// ---------------------------------------------------------------------------
// (g2) the files rustc actually compiled, from cargo's dep-info
// ---------------------------------------------------------------------------

/// The directory this test binary lives in (`target/<profile>/deps`), where cargo
/// leaves one rustc dep-info `.d` file per compiled unit. The read-only crates are
/// libraries of this package's dependency graph, so `cargo test` has compiled them.
fn deps_dir() -> PathBuf {
    std::env::current_exe()
        .expect("current_exe")
        .parent()
        .expect("deps dir")
        .to_path_buf()
}

/// Whether `p` sits under some checkout's `daemon/{crates,src,target}`.
fn in_a_daemon_tree(p: &Path) -> bool {
    let parts: Vec<_> = p.components().map(|c| c.as_os_str().to_owned()).collect();
    parts
        .windows(2)
        .any(|w| w[0] == "daemon" && (w[1] == "crates" || w[1] == "src" || w[1] == "target"))
}

/// The files named by one dep-info file's first rule (`target: dep dep ..`,
/// spaces escaped as `\ `), made absolute against `daemon/` when relative.
fn dep_info_files(path: &Path) -> Vec<PathBuf> {
    let text = read(path);
    let rule = text.lines().next().expect("empty dep-info");
    let (_, deps) = rule.split_once(": ").expect("dep-info rule has a colon");
    let mut files = Vec::new();
    let mut cur = String::new();
    let mut chars = deps.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '\\' if chars.peek() == Some(&' ') => {
                cur.push(' ');
                chars.next();
            }
            ' ' => {
                if !cur.is_empty() {
                    files.push(std::mem::take(&mut cur));
                }
            }
            _ => cur.push(c),
        }
    }
    if !cur.is_empty() {
        files.push(cur);
    }
    files
        .into_iter()
        .filter_map(|f| {
            let p = PathBuf::from(f);
            let abs = if p.is_absolute() { p } else { daemon().join(p) };
            // A stale `.d` (left by a renamed or deleted file) names a file that is
            // not in the current compile, so it is skipped rather than failed on.
            let abs = abs.canonicalize().ok()?;
            // A target dir shared with, or restored from, another checkout lists that
            // checkout's `daemon/` files: those are not this compile's. Any other path
            // outside the repo is kept, so the callers can refuse it.
            let foreign = !abs.starts_with(repo().canonicalize().ok()?) && in_a_daemon_tree(&abs);
            (!foreign).then_some(abs)
        })
        .collect()
}

/// Every file rustc read for a read-only crate (sources, `include_str!` data,
/// clippy.toml), across every `.d` file for it in the deps dir (the test build, and
/// any clippy or ban-probe build that ran before it).
fn compiled_files(krate: &str) -> BTreeSet<PathBuf> {
    let prefix = format!("{}-", krate.replace('-', "_"));
    let mut out = BTreeSet::new();
    let mut units = 0;
    for e in fs::read_dir(deps_dir()).expect("read deps dir").flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        if name.starts_with(&prefix) && name.ends_with(".d") {
            units += 1;
            out.extend(dep_info_files(&e.path()));
        }
    }
    assert!(
        units > 0 && out.iter().any(|f| f.extension().is_some_and(|x| x == "rs")),
        "no dep-info for {krate} in {}: the compiled-file check must fail closed",
        deps_dir().display()
    );
    out
}

/// Every `.rs` file rustc compiled for a read-only crate.
fn compiled_sources(krate: &str) -> BTreeSet<PathBuf> {
    compiled_files(krate)
        .into_iter()
        .filter(|f| f.extension().is_some_and(|x| x == "rs"))
        .collect()
}

/// A compiled file's census key: `crates/..` relative to `daemon/`, or
/// `OUT_DIR/<name>` for the one build-script output.
fn compiled_key(krate: &str, file: &Path) -> Result<String, String> {
    let own = daemon().join("crates").join(krate).canonicalize().unwrap();
    if let Ok(rel) = file.strip_prefix(&own) {
        let rel = rel.to_string_lossy().replace('\\', "/");
        // The lexer-based write guard walks `src/`; the probe is the only other file.
        if rel.starts_with("src/") || rel == "ban_probe.rs" {
            return Ok(format!("crates/{krate}/{rel}"));
        }
        return Err(format!(
            "{} is under the crate but outside src/",
            file.display()
        ));
    }
    let name = file.file_name().unwrap().to_string_lossy();
    let in_out_dir = file.to_string_lossy().contains(&format!("/build/{krate}-"))
        && file.to_string_lossy().contains("/out/");
    if krate == "relay-proto" && in_out_dir && name == "relay.v1.rs" {
        return Ok("OUT_DIR/relay.v1.rs".to_string());
    }
    Err(format!("{} is outside crates/{krate}/", file.display()))
}

