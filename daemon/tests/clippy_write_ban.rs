/// Non-`.rs` files a read-only crate may read besides its own: the root clippy
/// config and workspace manifest (clippy reads `rust-version` from it), and the two
/// `include_str!` Policy fixtures its tests parse.
const ALLOWED_DATA_FILES: &[&str] = &[
    "clippy.toml",
    "Cargo.toml",
    "policy.example.toml",
    "policy.default.toml",
];

// ---------------------------------------------------------------------------
// (g3) conditional compilation in the read-only crates
// ---------------------------------------------------------------------------

/// Every `cfg`/`cfg_attr` attribute the read-only crates may carry, whitespace
/// removed and without the leading `#`/`#!`. clippy lints one configuration (debug,
/// host), so code gated on anything else (`not(debug_assertions)`, a `target_*`)
/// could hold a write no lint ever sees. Each entry is a cfg that exists today:
const ALLOWED_CFGS: &[&str] = &[
    // test-only code (fixtures write files; never in the shipped build).
    "[cfg(test)]",
    // the probe mount (ban_probe.rs, pinned exactly below) and its feature.
    r#"[cfg(feature="ban-probe")]"#,
    // decision_log's JOURNALCTL_PATTERN, and relay-ops' `TemplateSet::{for_test,
    // empty_static}`, reachable from the bin's tests.
    r#"[cfg(any(test,feature="test-util"))]"#,
    // relay-policy's `forbid(unsafe_code)` outside tests.
    "[cfg_attr(not(test),forbid(unsafe_code))]",
];

/// The `cfg`/`cfg_attr` attributes of `src` that are not allowlisted, plus any
/// `cfg!` macro use.
fn unlisted_cfgs(src: &str) -> Vec<String> {
    let scrubbed = scrub(src, false);
    let mut bad: Vec<String> = attributes(&scrubbed)
        .into_iter()
        .filter(|a| a.starts_with("[cfg(") || a.starts_with("[cfg_attr("))
        .filter(|a| !ALLOWED_CFGS.contains(&a.as_str()))
        .collect();
    let mac = Regex::new(r"\b(r#)?cfg\s*!").unwrap();
    bad.extend(mac.find_iter(&scrubbed).map(|_| "cfg!(..)".to_string()));
    // A macro can emit an attribute from a `$c:meta` fragment, which no text scan of
    // the attribute list can resolve; none exists in these crates, so none is allowed.
    let defs = Regex::new(r"\bmacro_rules\b|\bmacro\s+\w").unwrap();
    bad.extend(
        defs.find_iter(&scrubbed)
            .map(|_| "macro definition".to_string()),
    );
    // Checked with string literals blanked: a `$` inside one (a thiserror message
    // quoting a regex, `#[error("must match ^[a-z]$")]`) is text, not a fragment.
    bad.extend(
        attributes(&scrub(src, true))
            .into_iter()
            .filter(|a| a.contains('$'))
            .map(|a| format!("attribute built from a macro fragment: {a}")),
    );
    bad
}

