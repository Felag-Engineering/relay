//! Smoke test that the read-only crates' filesystem-write ban is present, and
//! that nothing quietly switches it off (#889; invariants 1 and 2).
//!
//! `relay-policy`, `relay-log`, `relay-proto`, `relay-exec` and `relay-ops` are
//! read-only BY CONSTRUCTION: their `clippy.toml` `disallowed-methods` bans every
//! filesystem-write entry point, and the workspace lint level makes a hit a build
//! error. That is only as strong as the files that carry it, so this test pins
//! them. `scripts/clippy-ban-probe.sh` (`make check-daemon-bans`) proves each entry
//! FIRES; this proves the configuration around it cannot be removed or bypassed
//! without a test failing. Two sites spawn a process (invariant 1), each reviewed:
//! `relay-exec`'s one `Command::new`, under a statement-level allow, and the bin's
//! `join` spawn module, whose whole spawn is one allowed, pinned function.
//!
//! # It proves
//!
//! * (a) the only clippy configuration files are the root's and the read-only
//!   crates' own, no `.cargo/config*` exists in `daemon/` or at the repo root, and
//!   neither the Makefile nor any workflow or action sets `CLIPPY_CONF_DIR`,
//!   allows or force-warns a lint, caps lints, sets `RUSTFLAGS`, or downgrades
//!   `disallowed_methods` outside the probe script;
//! * (b) the read-only crates' `clippy.toml` files are byte-identical, and each
//!   carries every root entry (the exec ban: the nearest `clippy.toml` REPLACES
//!   a parent's, it does not merge) plus the pinned write ban, and the root and each
//!   copy carry the pinned exec ban, with `allow-invalid` on `libc::execveat` only;
//! * (c) every workspace member opts into the workspace lints, `disallowed_methods`
//!   is `deny` there, and the key set of `[workspace.lints.clippy]` is exactly
//!   pinned (a higher-priority group `allow` would override the ban);
//! * (d) `relay-test-support` (which writes files) is only ever a
//!   `[dev-dependencies]` entry, no normal dependency enables `test-util` or
//!   `ban-probe`, and every member is `publish = false`;
//! * (e) each read-only crate depends only on its own pinned first-party crates
//!   (`relay-policy` on `{relay-proto, relay-log}`; `relay-exec` on
//!   `{relay-proto}`; `relay-ops` on `{relay-proto, relay-policy, relay-exec,
//!   relay-log}`; `relay-log` and `relay-proto` on none);
//! * (f) `rustix` keeps EXACTLY `features = ["process", "termios"]` workspace-wide: Cargo
//!   unifies features, so one member enabling `fs` or `use-libc` would break the
//!   property `policy_never_opened_for_write.rs` and the executor rely on;
//! * (g) the set of lint suppressions that could hide a write or exec ban is
//!   exactly the pinned map, in both directions, over EVERY `.rs` file under each
//!   crate (not only `src/`); `#[path = ..]` and `include!` are pinned the same
//!   way (a module mounted from outside the walked tree would escape the census);
//!   and `relay-proto/src/lib.rs` is exactly the generated-module wrapper;
//!   production suppressions (each pinned to the statement it covers) are pinned
//!   apart from those inside `#[cfg(test)]` items (an item only: a `#[cfg(test)]` on
//!   a statement, block, match arm or macro call does not make anything test code),
//!   so a test allow cannot be moved onto production code at an unchanged count;
//! * (h) the spawn family (`Command`, `pre_exec`, libc `exec*`/`fork`/`clone`/`system`/
//!   `syscall`, `SYS_execve`-style numbers) appears only at the two sanctioned sites,
//!   `relay-exec`'s `executor.rs` and the bin's `join` spawn module, in every crate and
//!   the bin, whatever lint allow is in scope. The
//!   regex catches a `Command` alias (the alias names `Command` in its `use`),
//!   brace-imported libc names, and bare `system(`/`syscall(` calls. It misses a
//!   module alias such as `use libc as l; l::syscall`; clippy's resolved-path ban
//!   (which resolves `l::syscall` to `libc::syscall`) and the `unsafe` census (i),
//!   since any libc call needs `unsafe`, back that case;
//! * (i) the `unsafe` census: every `unsafe` in the daemon (the bin and
//!   `relay-transport` pinned to none) is pinned, since an `unsafe` block can call a
//!   libc function the clippy.toml does not name;
//! * (j) `file.read`'s one open in `relay-ops` is exactly the pinned statement, and the
//!   allow covers that statement only;
//! * (k) the probe script's crate list is exactly `READ_ONLY`;
//! * (l) `relay-ops` builds an `ExecRequest` only at the pinned sites: its write ban
//!   covers in-process writes, and a spawned child is bounded by Policy, Templates,
//!   `selfref` and the unit's `ProtectSystem`;
//! * (m) every member's `[features]` table is exactly pinned, and the shipped build
//!   (`-p relay-daemon`, host and musl) resolves no `test-util` or `ban-probe`.
//!
//! # It cannot see
//!
//! Attributes generated by a macro, and lint levels set through `RUSTFLAGS` in an
//! environment this repository does not control ((a) covers the repo's own
//! Makefile and CI). The textual spawn census (h) likewise cannot see an
//! identifier built by a macro; `macro_rules!` is refused in the read-only crates
//! and the bin's one exec suppression is pinned to the function it covers. The census (h) also misses a module alias
//! of `libc`; the clippy ban and the `unsafe` census catch it instead. A read-only
//! crate's non-test code that needs a write must be refused by review, not by this
//! test: the pinned map below is where a reviewer sees a new suppression.

