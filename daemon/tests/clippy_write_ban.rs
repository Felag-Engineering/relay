#[test]
fn suppression_scanner_flags_every_form_and_ignores_text() {
    let flagged = [
        "#[allow(clippy::disallowed_methods)]\nfn f() {}",
        "#[allow(\n    clippy::disallowed_methods,\n    reason = \"x\"\n)]\nfn f() {}",
        "#[allow(clippy :: disallowed_methods)] fn f() {}",
        "#![allow(clippy::all)]",
        "#[allow(clippy::style)] fn f() {}",
        "#[allow(warnings)] fn f() {}",
        "#[expect(clippy::disallowed_methods)] fn f() {}",
        "#[warn(clippy::disallowed_methods)] fn f() {}",
        "#![cfg_attr(not(test), allow(clippy::style))]",
        "#[cfg_attr(feature = \"x\", allow(clippy::disallowed_methods))] fn f() {}",
        "#[ allow ( clippy::disallowed_methods ) ] fn f() {}",
        "let s = 1; #[allow(clippy::disallowed_methods)] let x = f();",
    ];
    for src in flagged {
        assert_eq!(suppressions(src), 1, "not flagged: {src:?}");
    }
    let ignored = [
        "// #[allow(clippy::disallowed_methods)]\nfn f() {}",
        "/* #[allow(clippy::all)] */ fn f() {}",
        "const S: &str = \"#[allow(clippy::disallowed_methods)]\";",
        "const S: &str = r#\"#[allow(clippy::all)]\"#;",
        "#[allow(dead_code)] fn f() {}",
        "#![cfg_attr(not(test), forbid(unsafe_code))]",
        "#[deny(clippy::disallowed_methods)] fn f() {}",
        "fn f<'a>(x: &'a str) { let c = '#'; }",
    ];
    for src in ignored {
        assert_eq!(suppressions(src), 0, "wrongly flagged: {src:?}");
    }
}

/// `toml::Value` has `pointer`-less nested lookup; this keeps the call sites flat.
trait Nested {
    fn pointer_str(&self, path: &[&str]) -> Option<&str>;
}

impl Nested for Value {
    fn pointer_str(&self, path: &[&str]) -> Option<&str> {
        let mut cur = self;
        for key in path {
            cur = cur.get(*key)?;
        }
        cur.as_str()
    }
}
