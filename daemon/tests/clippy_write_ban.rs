//! Smoke test that the read-only crates' filesystem-write ban is present, and
//! that nothing quietly switches it off (#889; invariants 1 and 2).
//!
//! `relay-policy`, `relay-log` and `relay-proto` (and, once they exist, `relay-exec`
//! and `relay-ops`) are read-only BY CONSTRUCTION: their `clippy.toml` `disallowed-methods` bans every
//! filesystem-write entry point, and the workspace lint level makes a hit a build
//! error. That is only as strong as the files that carry it, so this test pins
//! them. `scripts/clippy-ban-probe.sh` (`make check-daemon-bans`) proves each entry
//! FIRES; this proves the configuration around it cannot be removed or bypassed
//! without a test failing.
//!
//! # It proves
//!
//! * (a) the only clippy configuration files are the root's and the read-only
//!   crates' own, no `.cargo/config*` exists in `daemon/` or at the repo root, and
//!   neither the Makefile nor any workflow or action sets `CLIPPY_CONF_DIR`,
//!   allows or force-warns a lint, caps lints, sets `RUSTFLAGS`, or downgrades
//!   `disallowed_methods` outside the probe script;
//! * (b) the read-only crates' `clippy.toml` files are byte-identical, and each
//!   carries every root entry (the exec ban: the nearest `clippy.toml` REPLACES
//!   a parent's, it does not merge) plus the pinned write ban;
//! * (c) every workspace member opts into the workspace lints, `disallowed_methods`
//!   is `deny` there, and the key set of `[workspace.lints.clippy]` is exactly
//!   pinned (a higher-priority group `allow` would override the ban);
//! * (d) `relay-test-support` (which writes files) is only ever a
//!   `[dev-dependencies]` entry, no normal dependency enables `test-util` or
//!   `ban-probe`, and every member is `publish = false`;
//! * (e) each read-only crate depends only on its own pinned first-party crates
//!   (`relay-policy` on `{relay-proto, relay-log}`; `relay-log` and `relay-proto`
//!   on none);
//! * (f) `rustix` keeps EXACTLY `features = ["process"]` workspace-wide: Cargo
//!   unifies features, so one member enabling `fs` or `use-libc` would break the
//!   property `policy_never_opened_for_write.rs` and the executor rely on;
//! * (g) the set of lint suppressions that could hide a write or exec ban is
//!   exactly the pinned map, in both directions, over EVERY `.rs` file under each
//!   crate (not only `src/`); `#[path = ..]` and `include!` are pinned the same
//!   way (a module mounted from outside the walked tree would escape the census);
//!   and `relay-proto/src/lib.rs` is exactly the generated-module wrapper.
//!
//! # It cannot see
//!
//! Attributes generated by a macro, and lint levels set through `RUSTFLAGS` in an
//! environment this repository does not control ((a) covers the repo's own
//! Makefile and CI). A read-only crate's non-test code that needs a write must
//! be refused by review, not by this test: the pinned map below is where a
//! reviewer sees a new suppression.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use regex::Regex;
use toml::Value;

/// The crates whose `clippy.toml` carries the write ban. Step 2 of #889 adds
/// `relay-exec` and `relay-ops`.
const READ_ONLY: &[&str] = &["relay-policy", "relay-log", "relay-proto"];

/// First-party crates one read-only crate may depend on (normal and build
/// dependencies). Per crate, so a leaf cannot quietly grow an edge to a crate with a
/// wider surface. Step 2 adds an arm for each crate it makes read-only.
fn may_depend_on(krate: &str) -> &'static [&'static str] {
    match krate {
        "relay-policy" => &["relay-proto", "relay-log"],
        "relay-log" | "relay-proto" => &[],
        other => panic!("no first-party dependency allowlist for read-only crate {other}"),
    }
}

fn daemon() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn repo() -> PathBuf {
    daemon()
        .parent()
        .expect("daemon has a parent")
        .to_path_buf()
}

fn read(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()))
}

fn parse(path: &Path) -> Value {
    toml::from_str(&read(path)).unwrap_or_else(|e| panic!("parse {}: {e}", path.display()))
}

/// Every workspace member directory name under `crates/`, sorted.
fn members() -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(daemon().join("crates"))
        .expect("read daemon/crates")
        .map(|e| e.expect("dir entry").path())
        .filter(|p| p.is_dir())
        .map(|p| p.file_name().unwrap().to_string_lossy().into_owned())
        .collect();
    names.sort();
    names
}

/// `(label, manifest)` for the root and every member.
fn manifests() -> Vec<(String, Value)> {
    let mut out = vec![(
        "relay-daemon".to_string(),
        parse(&daemon().join("Cargo.toml")),
    )];
    for m in members() {
        let path = daemon().join("crates").join(&m).join("Cargo.toml");
        out.push((m, parse(&path)));
    }
    out
}

/// The dependency tables of one manifest, as `(table path, table)`: the three
/// top-level ones and the same three under every `[target.*]`.
fn dep_tables(manifest: &Value) -> Vec<(String, &toml::Table)> {
    let mut out = Vec::new();
    for kind in ["dependencies", "build-dependencies", "dev-dependencies"] {
        if let Some(t) = manifest.get(kind).and_then(Value::as_table) {
            out.push((kind.to_string(), t));
        }
    }
    if let Some(targets) = manifest.get("target").and_then(Value::as_table) {
        for (cfg, body) in targets {
            for kind in ["dependencies", "build-dependencies", "dev-dependencies"] {
                if let Some(t) = body.get(kind).and_then(Value::as_table) {
                    out.push((format!("target.{cfg}.{kind}"), t));
                }
            }
        }
    }
    out
}

fn is_dev(table: &str) -> bool {
    table == "dev-dependencies" || table.ends_with(".dev-dependencies")
}

fn features_of(dep: &Value) -> Vec<String> {
    dep.get("features")
        .and_then(Value::as_array)
        .map(|a| {
            a.iter()
                .filter_map(|v| v.as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

