/// Blanks comments, and (when `blank_literals`) the contents of string and char
/// literals, keeping every delimiter and every newline.
fn scrub(src: &str, blank_literals: bool) -> String {
    let c: Vec<char> = src.chars().collect();
    let n = c.len();
    let mut out = String::with_capacity(src.len());
    let blank = |out: &mut String, ch: char| out.push(if ch == '\n' { '\n' } else { ' ' });
    let mut i = 0;
    while i < n {
        let ch = c[i];
        // Line comment.
        if ch == '/' && c.get(i + 1) == Some(&'/') {
            while i < n && c[i] != '\n' {
                out.push(' ');
                i += 1;
            }
            continue;
        }
        // Block comment (nests).
        if ch == '/' && c.get(i + 1) == Some(&'*') {
            let mut depth = 0;
            while i < n {
                if c[i] == '/' && c.get(i + 1) == Some(&'*') {
                    depth += 1;
                    out.push_str("  ");
                    i += 2;
                } else if c[i] == '*' && c.get(i + 1) == Some(&'/') {
                    depth -= 1;
                    out.push_str("  ");
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    blank(&mut out, c[i]);
                    i += 1;
                }
            }
            continue;
        }
        // Raw string: r"..", r#".."#, br#".."#.
        let raw_start = if ch == 'r' {
            Some(i + 1)
        } else if ch == 'b' && c.get(i + 1) == Some(&'r') {
            Some(i + 2)
        } else {
            None
        };
        if let Some(mut j) = raw_start {
            let prev_ident = i > 0 && (c[i - 1].is_alphanumeric() || c[i - 1] == '_');
            let mut hashes = 0;
            while c.get(j) == Some(&'#') {
                hashes += 1;
                j += 1;
            }
            if !prev_ident && c.get(j) == Some(&'"') {
                out.extend(c[i..=j].iter());
                j += 1;
                loop {
                    if j >= n {
                        break;
                    }
                    if c[j] == '"' && (0..hashes).all(|k| c.get(j + 1 + k) == Some(&'#')) {
                        out.push('"');
                        out.extend(std::iter::repeat_n('#', hashes));
                        j += 1 + hashes;
                        break;
                    }
                    if blank_literals {
                        blank(&mut out, c[j]);
                    } else {
                        out.push(c[j]);
                    }
                    j += 1;
                }
                i = j;
                continue;
            }
        }
        // Plain string.
        if ch == '"' {
            out.push('"');
            i += 1;
            while i < n && c[i] != '"' {
                if c[i] == '\\' && i + 1 < n {
                    for k in 0..2 {
                        if blank_literals {
                            blank(&mut out, c[i + k]);
                        } else {
                            out.push(c[i + k]);
                        }
                    }
                    i += 2;
                    continue;
                }
                if blank_literals {
                    blank(&mut out, c[i]);
                } else {
                    out.push(c[i]);
                }
                i += 1;
            }
            if i < n {
                out.push('"');
                i += 1;
            }
            continue;
        }
        // Char literal (not a lifetime or label).
        if ch == '\'' {
            let close = if c.get(i + 1) == Some(&'\\') {
                (i + 2..n.min(i + 12)).find(|&k| c[k] == '\'')
            } else if c.get(i + 2) == Some(&'\'') {
                Some(i + 2)
            } else {
                None
            };
            if let Some(close) = close {
                out.push('\'');
                for &x in &c[i + 1..close] {
                    if blank_literals {
                        blank(&mut out, x);
                    } else {
                        out.push(x);
                    }
                }
                out.push('\'');
                i = close + 1;
                continue;
            }
        }
        out.push(ch);
        i += 1;
    }
    out
}

fn squeeze(s: &str) -> String {
    s.chars().filter(|c| !c.is_whitespace()).collect()
}

/// One `#[...]` / `#![...]` attribute of scrubbed source: its char range
/// (`start` is the `#`, `end` the closing `]`), whether it is an inner attribute, and
/// its text without whitespace.
struct Attr {
    start: usize,
    end: usize,
    inner: bool,
    text: String,
}

/// The text of every `#[...]` / `#![...]` attribute in scrubbed source,
/// bracket-balanced (so a multi-line attribute is one), whitespace removed.
fn attributes(scrubbed: &str) -> Vec<String> {
    let b: Vec<char> = scrubbed.chars().collect();
    attr_spans(&b).into_iter().map(|a| a.text).collect()
}

fn attr_spans(b: &[char]) -> Vec<Attr> {
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        if b[i] == '#' {
            let mut j = i + 1;
            let inner = b.get(j) == Some(&'!');
            if inner {
                j += 1;
            }
            while b.get(j).is_some_and(|c| c.is_whitespace()) {
                j += 1;
            }
            if b.get(j) == Some(&'[') {
                let mut depth = 0;
                let mut k = j;
                while k < b.len() {
                    match b[k] {
                        '[' => depth += 1,
                        ']' => {
                            depth -= 1;
                            if depth == 0 {
                                break;
                            }
                        }
                        _ => {}
                    }
                    k += 1;
                }
                // `r#cfg` is `cfg`: strip raw-identifier prefixes before any matching.
                let end = k.min(b.len() - 1);
                out.push(Attr {
                    start: i,
                    end,
                    inner,
                    text: squeeze(&b[j..=end].iter().collect::<String>()).replace("r#", ""),
                });
                i = k;
            }
        }
        i += 1;
    }
    out
}

/// How many attributes in `src` switch off a lint that guards a write or exec
/// ban: one that sets a lint level (`allow`, `expect`, `warn`, or any of them
/// inside a `cfg_attr`) naming `disallowed_methods`, `clippy::style`,
/// `clippy::all` or `warnings`.
fn suppressions(src: &str) -> usize {
    attributes(&scrub(src, true))
        .iter()
        .filter(|a| is_suppression(a))
        .count()
}

fn is_suppression(a: &str) -> bool {
    let level = ["allow(", "expect(", "warn(", "cfg_attr("]
        .iter()
        .any(|w| a.contains(w));
    let lint = [
        "disallowed_methods",
        "disallowed_method",
        "clippy::style",
        "clippy::all",
        "warnings",
    ]
    .iter()
    .any(|l| a.contains(l));
    level && lint
}

/// One suppression attribute, placed: whether it sits inside (or on) a
/// `#[cfg(test)]` item, and what it covers.
#[derive(Debug, PartialEq)]
struct Site {
    test: bool,
    /// The attribute text, whitespace removed, string contents blanked.
    attr: String,
    /// Production only: the squeezed text of the item or statement the attribute
    /// is attached to (attributes that follow it included); empty for an inner one.
    covered: String,
}

/// Whether the code starting at `from` begins with an item keyword (`fn`, `mod`,
/// `impl`, `pub`, …).
fn target_is_item_like(b: &[char], from: usize) -> bool {
    let mut i = from;
    while b.get(i).is_some_and(|c| c.is_whitespace()) {
        i += 1;
    }
    let word: String = b[i..]
        .iter()
        .take_while(|c| c.is_alphanumeric() || **c == '_')
        .collect();
    [
        "fn", "pub", "mod", "impl", "struct", "enum", "trait", "unsafe", "async", "extern",
        "const", "static", "use", "type", "union",
    ]
    .contains(&word.as_str())
}

/// Whether the attribute starting at `at` is in item or statement position: what
/// precedes it, ignoring whitespace, is `{`, `}`, `;`, `]` or nothing. Consecutive
/// outer attributes are grouped, so in practice that `]` closes an inner `#![...]`
/// attribute.
fn in_item_position(b: &[char], at: usize) -> bool {
    b[..at]
        .iter()
        .rev()
        .find(|c| !c.is_whitespace())
        .is_none_or(|c| matches!(c, '{' | '}' | ';' | ']'))
}

/// Where the item or statement that starts at `from` ends: at the `;` that closes
/// it, or (for a `fn`, `mod`, `impl` and the like) at the `}` that closes its body.
/// Brackets are balanced on literal-blanked text, so a brace in a string is not one.
fn item_end(b: &[char], from: usize) -> usize {
    let mut i = from;
    while b.get(i).is_some_and(|c| c.is_whitespace()) {
        i += 1;
    }
    let item_like = target_is_item_like(b, from);
    let mut depth = 0i32;
    while i < b.len() {
        match b[i] {
            '(' | '[' | '{' => depth += 1,
            ')' | ']' => depth -= 1,
            '}' => {
                depth -= 1;
                if depth == 0 && item_like {
                    return i;
                }
            }
            ';' if depth == 0 => return i,
            _ => {}
        }
        if depth < 0 {
            return i;
        }
        i += 1;
    }
    b.len().saturating_sub(1)
}

/// Every write- or exec-ban suppression in `src`, classified production or test.
/// An attribute group (consecutive outer attributes, in either order) holding
/// `#[cfg(test)]` makes its target, and everything in it, test code, but only when
/// that target is an item (`target_is_item_like`) and the group sits in item or
/// statement position (`in_item_position`).
///
/// A `#[cfg(test)]` on a bare block, an `if`/`match`, a `let`, a match arm or a
/// braced macro call creates no test span: `item_end` ends such a target only at
/// the next top-level `;`, so it would swallow the statement that follows. Any
/// suppression after it or inside it is classified production and must match the
/// production pin exactly. That is the fail-closed direction.
///
/// Position matters as much as the target. A `#[cfg(test)]` on a generic parameter
/// (`fn f<#[cfg(test)] const N: usize>()`), a function parameter, a field after a
/// `,` or an expression strips only that fragment, not the item around it, yet
/// `const N` reads as item-like and `item_end` would run on to the enclosing
/// `}`, swallowing production code after it. So the group counts only when the
/// first non-whitespace character before it is `{`, `}`, `;`, `]` or the start of
/// the file; after anything else (`<`, `,`, `(`, `=`) it is production, which is
/// the fail-closed direction.
///
/// One harmless case remains: a struct's first `pub` field follows `{` and reads as
/// item-like, so its span runs to the struct's closing `}`. A struct body holds no
/// runtime code, so nothing hidden there can write or spawn.
fn suppression_sites(src: &str) -> Vec<Site> {
    let scrubbed = scrub(src, true);
    let b: Vec<char> = scrubbed.chars().collect();
    let attrs = attr_spans(&b);
    // Per group of consecutive outer attributes: (first attr index, last attr index,
    // end of the item the group is attached to, whether that target is item-like).
    let mut groups: Vec<(usize, usize, usize, bool)> = Vec::new();
    let mut i = 0;
    while i < attrs.len() {
        if attrs[i].inner {
            i += 1;
            continue;
        }
        let mut j = i;
        while j + 1 < attrs.len()
            && !attrs[j + 1].inner
            && b[attrs[j].end + 1..attrs[j + 1].start]
                .iter()
                .all(|c| c.is_whitespace())
        {
            j += 1;
        }
        groups.push((
            i,
            j,
            item_end(&b, attrs[j].end + 1),
            target_is_item_like(&b, attrs[j].end + 1),
        ));
        i = j + 1;
    }
    let test_spans: Vec<(usize, usize)> = groups
        .iter()
        .filter(|(first, last, _, item_like)| {
            *item_like
                && in_item_position(&b, attrs[*first].start)
                && attrs[*first..=*last]
                    .iter()
                    .any(|a| a.text == "[cfg(test)]")
        })
        .map(|(first, _, end, _)| (attrs[*first].start, *end))
        .collect();
    let mut out = Vec::new();
    for (n, a) in attrs.iter().enumerate() {
        if !is_suppression(&a.text) {
            continue;
        }
        let test = test_spans
            .iter()
            .any(|(s, e)| a.start >= *s && a.start <= *e);
        let covered = groups
            .iter()
            .find(|(first, last, _, _)| (*first..=*last).contains(&n))
            .map(|(_, _, end, _)| squeeze(&b[a.end + 1..=*end].iter().collect::<String>()))
            .unwrap_or_default();
        out.push(Site {
            test,
            attr: a.text.clone(),
            covered: if test { String::new() } else { covered },
        });
    }
    out
}

/// Every `.rs` file the workspace members build, keyed by path relative to
/// `daemon/`: the root's `src/` and `build.rs`, and EVERYTHING under each
/// `crates/<c>/` (so a `build.rs`, a probe file, or a module mounted by
/// `#[path]` from outside `src/` is read too). `target/` is skipped.
fn sources() -> BTreeMap<String, String> {
    fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
        for e in fs::read_dir(dir).expect("read source dir") {
            let p = e.expect("dir entry").path();
            if p.is_dir() {
                if p.file_name().is_some_and(|n| n == "target") {
                    continue;
                }
                walk(&p, out);
            } else if p.extension().is_some_and(|x| x == "rs") {
                out.push(p);
            }
        }
    }
    let mut roots = vec![daemon().join("src")];
    roots.extend(members().iter().map(|m| daemon().join("crates").join(m)));
    let mut out = BTreeMap::new();
    for root in roots {
        let mut files = Vec::new();
        walk(&root, &mut files);
        assert!(!files.is_empty(), "{} holds no .rs file", root.display());
        for f in files {
            let rel = f
                .strip_prefix(daemon())
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            out.insert(rel, read(&f));
        }
    }
    out.insert("build.rs".to_string(), read(&daemon().join("build.rs")));
    out
}

