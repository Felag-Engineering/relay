fn find_named(dir: &Path, names: &[&str], out: &mut Vec<String>) {
    for e in fs::read_dir(dir).expect("read dir") {
        let p = e.expect("dir entry").path();
        let name = p.file_name().unwrap().to_string_lossy().into_owned();
        if p.is_dir() {
            // Build output and the standalone fuzz workspace are not part of this one.
            if name == "target" || name == "fuzz" || name == ".git" {
                continue;
            }
            find_named(&p, names, out);
        } else if names.contains(&name.as_str()) {
            out.push(
                p.strip_prefix(daemon())
                    .unwrap()
                    .to_string_lossy()
                    .replace('\\', "/"),
            );
        }
    }
}

fn files_under(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            files_under(&p, out);
        } else {
            out.push(p);
        }
    }
}

#[test]
fn clippy_config_files_are_exactly_the_expected_set() {
    let mut found = Vec::new();
    find_named(&daemon(), &["clippy.toml", ".clippy.toml"], &mut found);
    found.sort();
    let mut want: Vec<String> = vec!["clippy.toml".to_string()];
    want.extend(READ_ONLY.iter().map(|c| format!("crates/{c}/clippy.toml")));
    want.sort();
    assert_eq!(
        found, want,
        "the clippy configuration files under daemon/ must be exactly the root's plus the \
         read-only crates' own — a stray one silently replaces the config for its subtree"
    );

    // Cargo reads `.cargo/config*` from the working directory and every parent, so the
    // repo root counts as well as `daemon/`.
    for (dir, label) in [(daemon(), "daemon"), (repo(), "the repo root")] {
        for cfg in [".cargo/config", ".cargo/config.toml"] {
            assert!(
                !dir.join(cfg).exists(),
                "{label}/{cfg} must not exist: it could set rustflags or env that override clippy"
            );
        }
    }
}

#[test]
fn nothing_in_the_build_overrides_the_clippy_config() {
    let mut scripts: Vec<PathBuf> = vec![repo().join("Makefile")];
    files_under(&repo().join(".github/workflows"), &mut scripts);
    files_under(&repo().join(".github/actions"), &mut scripts);
    assert!(
        scripts.len() > 2,
        "found only {} files to check; the Makefile and workflows moved?",
        scripts.len()
    );
    for path in scripts {
        let mut text = read(&path);
        let name = path.strip_prefix(repo()).unwrap().display().to_string();
        if name == "Makefile" {
            text = without_the_release_rustflags(&text);
        }
        for (pattern, why) in loosening_patterns() {
            let re = Regex::new(pattern).expect("pattern compiles");
            if let Some(m) = re.find(&text) {
                panic!(
                    "{name} contains `{}` ({why}), which would loosen or redirect the clippy \
                     write ban (only scripts/clippy-ban-probe.sh may downgrade disallowed_methods)",
                    m.as_str()
                );
            }
        }
    }
}

/// The one sanctioned `RUSTFLAGS` in the Makefile: `build-daemon-release` hands rustc the
/// path-remapping flags that make the release artifact reproducible (#892). It is a
/// `cargo build`, never a clippy run, and its value is pinned here to exactly the two
/// `--remap-path-prefix` flags, so it can never carry a lint level. Both lines must appear
/// exactly once and verbatim; the scan then runs over the rest of the Makefile as usual.
/// Comment lines are dropped too: make passes neither a `#` line nor a recipe line that
/// make or the shell sees as a comment to any tool.
fn without_the_release_rustflags(makefile: &str) -> String {
    const DEFINITION: &str =
        "DAEMON_RELEASE_RUSTFLAGS := --remap-path-prefix=$(CURDIR)=/relay-src \
                              --remap-path-prefix=$(CARGO_HOME_DIR)=/cargo";
    const RECIPE: &str =
        "\tcd daemon && $(DAEMON_STAMP) CC_$(subst -,_,$(RELEASE_DAEMON_TARGET))=musl-gcc \
                          RUSTFLAGS=\"$(DAEMON_RELEASE_RUSTFLAGS)\" cargo build --release --locked \
                          -p relay-daemon --target $(RELEASE_DAEMON_TARGET)";
    let lines: Vec<&str> = makefile.lines().collect();
    for (pinned, what) in [
        (DEFINITION, "definition"),
        (RECIPE, "build-daemon-release recipe"),
    ] {
        let n = lines.iter().filter(|l| **l == pinned).count();
        assert_eq!(
            n, 1,
            "the release RUSTFLAGS {what} must appear exactly once, verbatim:\n{pinned}"
        );
    }
    lines
        .iter()
        .filter(|l| **l != RECIPE && !l.trim_start().starts_with('#'))
        .map(|l| l.replace("DAEMON_RELEASE_RUSTFLAGS", "DAEMON_RELEASE_FLAGS"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Flags that switch a clippy lint off, cap it, or hand rustc flags to the build.
fn loosening_patterns() -> [(&'static str, &'static str); 8] {
    [
        (r"CLIPPY_CONF_DIR", "redirects the clippy config"),
        (r"-A\s*(clippy|warnings)", "allows a lint"),
        (r"--allow(\s|=)", "allows a lint"),
        (r"--force-warn\b", "overrides a lint level"),
        (r"--cap-lints\b", "caps every lint"),
        (
            r"RUSTFLAGS",
            "passes rustc flags that can change lint levels",
        ),
        (r"-W\s*clippy::disallowed", "downgrades the write ban"),
        (r"--warn\s*clippy::disallowed", "downgrades the write ban"),
    ]
}

#[test]
fn the_loosening_patterns_catch_every_spelling() {
    let hits = [
        "cargo clippy -- -A clippy::disallowed_methods",
        "cargo clippy -- -Aclippy::all",
        "cargo clippy -- -A warnings",
        "cargo clippy -- --allow clippy::style",
        "cargo clippy -- --force-warn clippy::all",
        "cargo clippy -- --cap-lints allow",
        "RUSTFLAGS=\"-A warnings\" cargo clippy",
        "CLIPPY_CONF_DIR=/tmp cargo clippy",
        "cargo clippy -- -W clippy::disallowed_methods",
        "cargo clippy -- --warn clippy::disallowed_methods",
    ];
    for h in hits {
        assert!(
            loosening_patterns()
                .iter()
                .any(|(p, _)| Regex::new(p).unwrap().is_match(h)),
            "not caught: {h:?}"
        );
    }
    for ok in [
        "cargo clippy --workspace -- -D warnings",
        "grep -A3 foo file",
    ] {
        assert!(
            !loosening_patterns()
                .iter()
                .any(|(p, _)| Regex::new(p).unwrap().is_match(ok)),
            "wrongly caught: {ok:?}"
        );
    }
}

