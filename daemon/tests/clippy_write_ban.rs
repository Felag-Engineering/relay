/// The features cargo RESOLVES for every first-party crate in the shipped
/// (normal-edge) graph of the bin, as `(crate, features)`. Same invocation as
/// `resolved_rustix_features`, so it takes no build lock.
#[allow(clippy::disallowed_methods)] // test-only: spawns `cargo tree`, as resolved_rustix_features does
fn resolved_first_party_features(target: Option<&str>) -> Vec<(String, BTreeSet<String>)> {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    let mut cmd = std::process::Command::new(cargo);
    cmd.current_dir(daemon()).args([
        "tree",
        "--locked",
        "--offline",
        "-e",
        "normal",
        "--prefix",
        "none",
        "--no-dedupe",
        "-p",
        "relay-daemon",
        "-f",
        "{p} [{f}]",
    ]);
    if let Some(t) = target {
        cmd.args(["--target", t]);
    }
    let out = cmd.output().expect("run cargo tree");
    assert!(
        out.status.success(),
        "cargo tree failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter(|l| l.starts_with("relay-"))
        .map(|l| {
            let name = l.split_whitespace().next().unwrap().to_string();
            let features = l
                .rsplit_once('[')
                .expect("feature list")
                .1
                .trim_end_matches([']', ' '])
                .split(',')
                .filter(|f| !f.is_empty())
                .map(str::to_string)
                .collect();
            (name, features)
        })
        .collect()
}

#[test]
fn no_test_util_or_ban_probe_feature_resolves_in_the_shipped_build() {
    for target in [None, Some("x86_64-unknown-linux-musl")] {
        let resolved = resolved_first_party_features(target);
        for krate in [
            "relay-proto",
            "relay-log",
            "relay-policy",
            "relay-exec",
            "relay-ops",
            "relay-transport",
        ] {
            assert!(
                resolved.iter().any(|(n, _)| n == krate),
                "{krate} is missing from the shipped graph (target {target:?}): {resolved:?}"
            );
        }
        for (name, features) in &resolved {
            for banned in ["test-util", "ban-probe"] {
                assert!(
                    !features.contains(banned),
                    "{name} resolves with `{banned}` in the shipped build (target {target:?}, \
                     features {features:?}): test-only items would be compiled into the daemon"
                );
            }
        }
    }
}

/// `toml::Value` has `pointer`-less nested lookup; this keeps the call sites flat.
trait Nested {
    fn pointer_str(&self, path: &[&str]) -> Option<&str>;
}

impl Nested for Value {
    fn pointer_str(&self, path: &[&str]) -> Option<&str> {
        let mut cur = self;
        for key in path {
            cur = cur.get(*key)?;
        }
        cur.as_str()
    }
}
