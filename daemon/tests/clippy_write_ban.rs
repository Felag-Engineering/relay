/// Blanks comments, and (when `blank_literals`) the contents of string and char
/// literals, keeping every delimiter and every newline.
fn scrub(src: &str, blank_literals: bool) -> String {
    let c: Vec<char> = src.chars().collect();
    let n = c.len();
    let mut out = String::with_capacity(src.len());
    let blank = |out: &mut String, ch: char| out.push(if ch == '\n' { '\n' } else { ' ' });
    let mut i = 0;
    while i < n {
        let ch = c[i];
        // Line comment.
        if ch == '/' && c.get(i + 1) == Some(&'/') {
            while i < n && c[i] != '\n' {
                out.push(' ');
                i += 1;
            }
            continue;
        }
        // Block comment (nests).
        if ch == '/' && c.get(i + 1) == Some(&'*') {
            let mut depth = 0;
            while i < n {
                if c[i] == '/' && c.get(i + 1) == Some(&'*') {
                    depth += 1;
                    out.push_str("  ");
                    i += 2;
                } else if c[i] == '*' && c.get(i + 1) == Some(&'/') {
                    depth -= 1;
                    out.push_str("  ");
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    blank(&mut out, c[i]);
                    i += 1;
                }
            }
            continue;
        }
        // Raw string: r"..", r#".."#, br#".."#.
        let raw_start = if ch == 'r' {
            Some(i + 1)
        } else if ch == 'b' && c.get(i + 1) == Some(&'r') {
            Some(i + 2)
        } else {
            None
        };
        if let Some(mut j) = raw_start {
            let prev_ident = i > 0 && (c[i - 1].is_alphanumeric() || c[i - 1] == '_');
            let mut hashes = 0;
            while c.get(j) == Some(&'#') {
                hashes += 1;
                j += 1;
            }
            if !prev_ident && c.get(j) == Some(&'"') {
                out.extend(c[i..=j].iter());
                j += 1;
                loop {
                    if j >= n {
                        break;
                    }
                    if c[j] == '"' && (0..hashes).all(|k| c.get(j + 1 + k) == Some(&'#')) {
                        out.push('"');
                        out.extend(std::iter::repeat_n('#', hashes));
                        j += 1 + hashes;
                        break;
                    }
                    if blank_literals {
                        blank(&mut out, c[j]);
                    } else {
                        out.push(c[j]);
                    }
                    j += 1;
                }
                i = j;
                continue;
            }
        }
        // Plain string.
        if ch == '"' {
            out.push('"');
            i += 1;
            while i < n && c[i] != '"' {
                if c[i] == '\\' && i + 1 < n {
                    for k in 0..2 {
                        if blank_literals {
                            blank(&mut out, c[i + k]);
                        } else {
                            out.push(c[i + k]);
                        }
                    }
                    i += 2;
                    continue;
                }
                if blank_literals {
                    blank(&mut out, c[i]);
                } else {
                    out.push(c[i]);
                }
                i += 1;
            }
            if i < n {
                out.push('"');
                i += 1;
            }
            continue;
        }
        // Char literal (not a lifetime or label).
        if ch == '\'' {
            let close = if c.get(i + 1) == Some(&'\\') {
                (i + 2..n.min(i + 12)).find(|&k| c[k] == '\'')
            } else if c.get(i + 2) == Some(&'\'') {
                Some(i + 2)
            } else {
                None
            };
            if let Some(close) = close {
                out.push('\'');
                for &x in &c[i + 1..close] {
                    if blank_literals {
                        blank(&mut out, x);
                    } else {
                        out.push(x);
                    }
                }
                out.push('\'');
                i = close + 1;
                continue;
            }
        }
        out.push(ch);
        i += 1;
    }
    out
}

fn squeeze(s: &str) -> String {
    s.chars().filter(|c| !c.is_whitespace()).collect()
}

/// The text of every `#[...]` / `#![...]` attribute in scrubbed source,
/// bracket-balanced (so a multi-line attribute is one), whitespace removed.
fn attributes(scrubbed: &str) -> Vec<String> {
    let b: Vec<char> = scrubbed.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        if b[i] == '#' {
            let mut j = i + 1;
            if b.get(j) == Some(&'!') {
                j += 1;
            }
            while b.get(j).is_some_and(|c| c.is_whitespace()) {
                j += 1;
            }
            if b.get(j) == Some(&'[') {
                let mut depth = 0;
                let mut k = j;
                while k < b.len() {
                    match b[k] {
                        '[' => depth += 1,
                        ']' => {
                            depth -= 1;
                            if depth == 0 {
                                break;
                            }
                        }
                        _ => {}
                    }
                    k += 1;
                }
                // `r#cfg` is `cfg`: strip raw-identifier prefixes before any matching.
                out.push(
                    squeeze(&b[j..=k.min(b.len() - 1)].iter().collect::<String>())
                        .replace("r#", ""),
                );
                i = k;
            }
        }
        i += 1;
    }
    out
}

/// How many attributes in `src` switch off a lint that guards a write or exec
/// ban: one that sets a lint level (`allow`, `expect`, `warn`, or any of them
/// inside a `cfg_attr`) naming `disallowed_methods`, `clippy::style`,
/// `clippy::all` or `warnings`.
fn suppressions(src: &str) -> usize {
    attributes(&scrub(src, true))
        .iter()
        .filter(|a| {
            let level = ["allow(", "expect(", "warn(", "cfg_attr("]
                .iter()
                .any(|w| a.contains(w));
            let lint = [
                "disallowed_methods",
                "disallowed_method",
                "clippy::style",
                "clippy::all",
                "warnings",
            ]
            .iter()
            .any(|l| a.contains(l));
            level && lint
        })
        .count()
}

/// Every `.rs` file the workspace members build, keyed by path relative to
/// `daemon/`: the root's `src/` and `build.rs`, and EVERYTHING under each
/// `crates/<c>/` (so a `build.rs`, a probe file, or a module mounted by
/// `#[path]` from outside `src/` is read too). `target/` is skipped.
fn sources() -> BTreeMap<String, String> {
    fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
        for e in fs::read_dir(dir).expect("read source dir") {
            let p = e.expect("dir entry").path();
            if p.is_dir() {
                if p.file_name().is_some_and(|n| n == "target") {
                    continue;
                }
                walk(&p, out);
            } else if p.extension().is_some_and(|x| x == "rs") {
                out.push(p);
            }
        }
    }
    let mut roots = vec![daemon().join("src")];
    roots.extend(members().iter().map(|m| daemon().join("crates").join(m)));
    let mut out = BTreeMap::new();
    for root in roots {
        let mut files = Vec::new();
        walk(&root, &mut files);
        assert!(!files.is_empty(), "{} holds no .rs file", root.display());
        for f in files {
            let rel = f
                .strip_prefix(daemon())
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            out.insert(rel, read(&f));
        }
    }
    out.insert("build.rs".to_string(), read(&daemon().join("build.rs")));
    out
}

